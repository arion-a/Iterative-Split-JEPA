"""Verdicts for E72 (rules registered in docs/EVIDENCE.md, 'E72 registration'). Every failed line states observed, required and the gap.
    python experiments/analyse_e72.py ROOT      # ROOT holds results/nested/e72/{A,U}/K<K>_s0.5/main_seed*.json  -> ROOT/REPORT_E72.md"""
import os, sys
import numpy as np
sys.path.insert(0, os.path.dirname(__file__))
import analyse_e68_e71 as A
SLOW, ERR, KS = 0.86, 0.02, (11, 13, 16)
def rhos(K): return [round(float(1 - x), 4) for x in np.geomspace(0.8, 0.04, K)]
def slow_set(K): return [b for b in range(1, K + 1) if rhos(K)[b - 1] >= SLOW]              # layers (1-based); the last one is the core
def passes_S(r, K):
    ok = r["output_cov_min_eig"] >= A.HEALTH and r["slice"]["presence"][K - 1] >= A.PRES
    return ok and all(A.rung_clean(r, b)[0] for b in slow_set(K) if b < K)
def errs(r, K): return [abs(r["slice"]["rho_hat"][b - 1] - rhos(K)[b - 1]) for b in slow_set(K)]
def passes_R(r, K): return max(errs(r, K)) <= ERR
def passes_order(r, K):
    est = [r["slice"]["rho_hat"][b - 1] for b in slow_set(K)]; return all(x < y for x, y in zip(est, est[1:]))      # true speeds increase with the layer number
def verdict(root):
    md = ["# E72 report (generated by experiments/analyse_e72.py)", ""]; res = {}
    for K in KS:
        runs = A.load(f"{root}/results/nested/e72/A/K{K}_s0.5"); unt = A.load(f"{root}/results/nested/e72/U/K{K}_s0.5")
        res[K] = dict(S=[passes_S(r, K) for r in runs], R=[passes_R(r, K) for r in runs], O=[passes_order(r, K) for r in runs], n=len(runs), runs=runs, unt=unt)
    md += ["| K | slow layers | passes S | passes R | passes order |", "|---|---|---|---|---|"]
    for K in KS:
        x = res[K]; sl = slow_set(K); md.append(f"| {K} | {sl[0]} to {sl[-1]} | {sum(x['S'])} of {x['n']} | {sum(x['R'])} of {x['n']} | {sum(x['O'])} of {x['n']} |")
    lines = []
    for tag, key, need, what in (("(a) slow-rung criterion S", "S", 4, "arm A passes S"), ("(b) rate recovery R (every slow slice within 0.02)", "R", 3, "arm A passes R"), ("(c) order of the speeds", "O", 3, "arm A passes order")):
        bad = [f"K = {K}: {sum(res[K][key])} of {res[K]['n']}, required {need}, short by {need - sum(res[K][key])} seed(s)" for K in KS if sum(res[K][key]) < need]
        lines.append((tag, not bad, "; ".join(bad)))
    md += ["", f"**E72 slow-rung criterion verdict: {'CONFIRMED' if lines[0][1] else 'REFUTED'}.** " + (f"{lines[0][0]} NOT met: {lines[0][2]}" if not lines[0][1] else "(a) met at every K."),
           f"**E72 rate-recovery verdict: {'CONFIRMED' if lines[1][1] else 'REFUTED'}.** " + (f"{lines[1][0]} NOT met: {lines[1][2]}" if not lines[1][1] else "(b) met at every K."),
           f"**E72 order verdict (separate): {'CONFIRMED' if lines[2][1] else 'REFUTED'}.** " + (f"{lines[2][0]} NOT met: {lines[2][2]}" if not lines[2][1] else "(c) met at every K."), ""]
    md += ["Deviations of failing seeds:"]
    for K in KS:
        for r in res[K]["runs"]:
            if not passes_S(r, K):
                bad = [f"rung {b}: {A.rung_clean(r, b)[1]}" for b in slow_set(K) if b < K and not A.rung_clean(r, b)[0]]
                if r["slice"]["presence"][K - 1] < A.PRES: bad.append(f"core presence {r['slice']['presence'][K - 1]:.3f} < {A.PRES} (short {A.PRES - r['slice']['presence'][K - 1]:.3f})")
                if r["output_cov_min_eig"] < A.HEALTH: bad.append(f"health {r['output_cov_min_eig']:.3f} < {A.HEALTH}")
                md.append(f"- S, K = {K}, seed {r['seed']}: " + "; ".join(bad))
            if not passes_R(r, K):
                e = errs(r, K); i = int(np.argmax(e)); md.append(f"- R, K = {K}, seed {r['seed']}: largest error {e[i]:.3f} > {ERR} (over by {e[i] - ERR:.3f}) at layer {slow_set(K)[i]} (true {rhos(K)[slow_set(K)[i] - 1]:.3f}, estimated {r['slice']['rho_hat'][slow_set(K)[i] - 1]:.3f})")
            if not passes_order(r, K): md.append(f"- order, K = {K}, seed {r['seed']}: estimated speeds {[round(r['slice']['rho_hat'][b - 1], 3) for b in slow_set(K)]} are not increasing")
    md += ["", "## Per slow slice (mean over seeds; U = untrained control)", "", "| K | layer | true rho | A: mean estimate | A: mean error | A: largest error | U: mean estimate |", "|---|---|---|---|---|---|---|"]
    for K in KS:
        for b in slow_set(K):
            ea = [r["slice"]["rho_hat"][b - 1] for r in res[K]["runs"]]; eu = [r["slice"]["rho_hat"][b - 1] for r in res[K]["unt"]]; tr = rhos(K)[b - 1]
            md.append(f"| {K} | {b}{' (core)' if b == K else ''} | {tr:.3f} | {np.mean(ea):.3f} | {np.mean(np.abs(np.array(ea) - tr)):.3f} | {np.max(np.abs(np.array(ea) - tr)):.3f} | {np.mean(eu):.3f} |")
    open(f"{root}/REPORT_E72.md", "w").write("\n".join(md) + "\n"); print("\n".join(md[:12]))
    return res, lines
if __name__ == "__main__": verdict(sys.argv[1])
