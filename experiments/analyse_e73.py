"""E73 results (rules registered in docs/EVIDENCE.md, 'E73 registration'): speed read-back from the eigen-split blocks.
    python experiments/analyse_e73.py results/e73      -> results/e73/REPORT_E73.md
Judged: (a) recipe P at strength 0.5 and (b) recipe Q at strength 1: every block |error| <= 0.03 on at least 4 (a) / 3 (b) of 5 seeds. All cells reported."""
import glob, json, sys
import numpy as np
RHO, NAMES, TOL = [0.2, 0.7, 0.95], ["texture (rung 1)", "identity (rung 2)", "category (core)"], 0.03
def load(folder): return sorted((json.load(open(f)) for f in glob.glob(f"{folder}/main_seed*.json")), key=lambda r: r["seed"])
def main(root):
    cells = {(r, s): load(f"{root}/{r}_s{s}") for r in "PQ" for s in ("0.5", "1")}
    md = ["# E73 report (generated by experiments/analyse_e73.py)", ""]
    for (rec, st), runs in cells.items():
        est = np.array([r["block_rho_hat"] for r in runs]); ang = np.array([[g["angle_deg"] for g in r["rungs"]] for r in runs]); n = len(runs)
        md += [f"## Recipe {rec} ({'paper recipe, mirror encoder' if rec == 'P' else 'generic MLP, predictive loss'}), coupling strength {st}, {n} seeds", "",
               "| Block | True speed | Recovered (mean) | Seed spread (sd) | Lowest to highest | Mean error | Angle of the block to the true layer (mean degrees) |", "|---|---|---|---|---|---|---|"]
        for j in range(3):
            a = f"{ang[:, j].mean():.1f}" if j < 2 else "-"
            md.append(f"| {NAMES[j]} | {RHO[j]:.2f} | {est[:, j].mean():.3f} | {est[:, j].std(ddof=1):.3f} | {est[:, j].min():.3f} to {est[:, j].max():.3f} | {est[:, j].mean() - RHO[j]:+.3f} | {a} |")
        md += ["", "Per seed (recovered speeds of texture, identity, category; error in brackets):", ""]
        for r, e in zip(runs, est): md.append(f"- seed {r['seed']}: " + ", ".join(f"{e[j]:.3f} ({e[j] - RHO[j]:+.3f})" for j in range(3)))
        md.append("")
    def passes(rec, st): return sum(bool(np.all(np.abs(np.array(r["block_rho_hat"]) - RHO) <= TOL)) for r in cells[(rec, st)])
    pa, pb = passes("P", "0.5"), passes("Q", "1")
    ok_a, ok_b = pa >= 4, pb >= 3
    def worst(rec, st): return max(np.max(np.abs(np.array(r["block_rho_hat"]) - RHO)) for r in cells[(rec, st)])
    wa, wb = worst("P", "0.5"), worst("Q", "1")
    la = "met" if ok_a else "NOT met, short by %d seed(s); largest error on any seed %.3f, over by %.3f" % (4 - pa, wa, wa - TOL)
    lb = "met" if ok_b else "NOT met, short by %d seed(s); largest error on any seed %.3f, over by %.3f" % (3 - pb, wb, wb - TOL)
    md += ["## Registered lines", "",
           "- (a) recipe P, strength 0.5: every block within %g on %d of 5 seeds, required 4: **%s**" % (TOL, pa, la),
           "- (b) recipe Q, strength 1: every block within %g on %d of 5 seeds, required 3: **%s**" % (TOL, pb, lb),
           "- E73 verdict: **%s**" % ("CONFIRMED" if ok_a and ok_b else "REFUTED"), ""]
    open(f"{root}/REPORT_E73.md", "w").write("\n".join(md)); print("\n".join(md))
if __name__ == "__main__": main(sys.argv[1])
